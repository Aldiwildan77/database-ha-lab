#!/usr/bin/env python3
"""Generates jmeter/scenarios/*.jmx. All scenarios share scripts/transaction.groovy; they differ in
thread groups and default read ratio. Every default can be overridden with -J<property>."""

import os
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))

SCENARIOS = {
    #  name: (read_ratio, threads, rampup, duration, extra thread groups)
    "baseline": ("0.5", 2, 10, 120, []),
    "read-heavy": ("0.8", 16, 30, 300, []),
    "write-heavy": ("0.2", 16, 30, 300, []),
    "mixed-workload": ("0.5", 16, 30, 300, []),
    "spike-test": ("0.5", 8, 10, 300, ["spike"]),
    "soak-test": ("0.5", 16, 60, 3600, []),
    "failover-test": ("0.2", 8, 10, 300, []),
    "network-disruption": ("0.5", 8, 10, 300, []),
    # 4 threads for 10 min; waves stack on top: 16 threads at 2-8 min, 48 at 4-6 min, +64 burst at 5:00-5:30.
    "wave-test": ("0.5", 4, 10, 600, ["waves"]),
}


def thread_group(name, threads, rampup, duration, delay, sampler):
    return f"""
      <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="{name}">
        <stringProp name="ThreadGroup.on_sample_error">continue</stringProp>
        <elementProp name="ThreadGroup.main_controller" elementType="LoopController" guiclass="LoopControlPanel" testclass="LoopController" testname="Loop">
          <boolProp name="LoopController.continue_forever">false</boolProp>
          <intProp name="LoopController.loops">-1</intProp>
        </elementProp>
        <stringProp name="ThreadGroup.num_threads">{threads}</stringProp>
        <stringProp name="ThreadGroup.ramp_time">{rampup}</stringProp>
        <boolProp name="ThreadGroup.scheduler">true</boolProp>
        <stringProp name="ThreadGroup.duration">{duration}</stringProp>
        <stringProp name="ThreadGroup.delay">{delay}</stringProp>
        <boolProp name="ThreadGroup.same_user_on_next_iteration">true</boolProp>
      </ThreadGroup>
      <hashTree>{sampler}
      </hashTree>"""


def sampler(name, script, params):
    return f"""
        <JSR223Sampler guiclass="TestBeanGUI" testclass="JSR223Sampler" testname="{name}">
          <stringProp name="scriptLanguage">groovy</stringProp>
          <stringProp name="parameters">{escape(params)}</stringProp>
          <stringProp name="filename">${{__P(lab_script_dir,jmeter/scripts)}}/{script}</stringProp>
          <stringProp name="cacheKey">true</stringProp>
          <stringProp name="script"></stringProp>
        </JSR223Sampler>
        <hashTree/>"""


def plan(name, groups):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by jmeter/build-scenarios.py. Do not edit by hand. -->
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.6.3">
  <hashTree>
    <TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="{name}">
      <elementProp name="TestPlan.user_defined_variables" elementType="Arguments" guiclass="ArgumentsPanel" testclass="Arguments" testname="User Defined Variables">
        <collectionProp name="Arguments.arguments"/>
      </elementProp>
      <boolProp name="TestPlan.functional_mode">false</boolProp>
      <boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
    </TestPlan>
    <hashTree>{groups}
    </hashTree>
  </hashTree>
</jmeterTestPlan>
"""


def main():
    out = os.path.join(HERE, "scenarios")
    for name, (ratio, threads, rampup, duration, extra) in SCENARIOS.items():
        s = sampler("transaction", "transaction.groovy", ratio)
        groups = thread_group("load", f"${{__P(threads,{threads})}}", f"${{__P(rampup,{rampup})}}",
                              f"${{__P(duration,{duration})}}", "0", s)
        if "spike" in extra:
            groups += thread_group("spike", "${__P(spike_threads,64)}", "${__P(spike_rampup,1)}",
                                   "${__P(spike_duration,60)}", "${__P(spike_at,120)}", s)
        if "waves" in extra:
            groups += thread_group("wave1", "${__P(wave1_threads,12)}", "30", "360", "120", s)
            groups += thread_group("wave2", "${__P(wave2_threads,32)}", "30", "120", "240", s)
            groups += thread_group("burst", "${__P(spike_threads,64)}", "1", "30", "300", s)
        with open(os.path.join(out, f"{name}.jmx"), "w") as fh:
            fh.write(plan(name, groups))
    prep = thread_group("prepare", "1", "0", "${__P(prepare_timeout,1800)}", "0",
                        sampler("prepare", "prepare.groovy", ""))
    prep = prep.replace('<intProp name="LoopController.loops">-1</intProp>', '<intProp name="LoopController.loops">1</intProp>')
    with open(os.path.join(out, "prepare.jmx"), "w") as fh:
        fh.write(plan("prepare", prep))
    print("generated", len(SCENARIOS) + 1, "plans")


if __name__ == "__main__":
    main()
