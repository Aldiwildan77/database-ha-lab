#!/usr/bin/env bash
# Local smoke-test lab: N Ubuntu 24.04 VMs on this Mac (Lima, vzNAT network) and a matching config dir.
#   local-lab.sh up [N=3] [ENGINE=postgres] [HA=patroni] | down | status
# Then: export LAB_CONFIG_DIR=local/lab-vms/config and run make provision, make ha, ... as usual.
# Apple silicon VMs are aarch64: MySQL (x86_64 only in this lab) is not supported here; MariaDB and PostgreSQL are.
source "$(dirname "$0")/lib.sh"
require limactl

DIR="${LAB_ROOT}/local/lab-vms"
CFG="${DIR}/config"
N="${N:-3}"
ENGINE="${ENGINE:-postgres}"
HA="${HA:-patroni}"
CPUS="${CPUS:-2}"
MEM="${MEM:-4GiB}"
DISK="${DISK:-30GiB}"

vms() { limactl list --format '{{.Name}}' 2>/dev/null | grep -E '^halab-[0-9]+$' || true; }
# eth0: user-v2 (VM to VM: replication, failover); lima1: vzNAT (this Mac to VM: SSH, clients, monitoring).
ip_of() { limactl shell "$1" ip -4 -o addr show "${2:-lima1}" | awk '{split($4, a, "/"); print a[1]}'; }

up() {
  for i in $(seq 1 "$N"); do
    name="halab-$i"
    if ! grep -qx "$name" <<<"$(limactl list --format '{{.Name}}' 2>/dev/null)"; then
      limactl create --tty=false --name="$name" --vm-type=vz \
        --set ".cpus=${CPUS} | .memory=\"${MEM}\" | .disk=\"${DISK}\" | .mounts=[] | .networks=[{\"lima\": \"user-v2\"}, {\"vzNAT\": true}] | .containerd.system=false | .containerd.user=false" \
        template:ubuntu-24.04
    fi
    limactl start --tty=false "$name" >/dev/null
    ssh-keygen -R "$(ip_of "$name")" >/dev/null 2>&1 || true   # recreated VMs reuse IPs with new host keys
    green "$name up: $(ip_of "$name")"
  done
  write_config
}

write_config() {
  mkdir -p "$CFG"
  local key="${HOME}/.lima/_config/user" user host_cidr mesh_cidr
  user="$(limactl shell halab-1 whoami)"
  host_cidr="$(ip_of halab-1 | awk -F. '{print $1"."$2"."$3".0/24"}')"
  mesh_cidr="$(ip_of halab-1 eth0 | awk -F. '{print $1"."$2"."$3".0/24"}')"
  {
    echo "# Generated by local/scripts/local-lab.sh; regenerated on every 'up'."
    echo "environment: {name: local, network: mesh, operator_network: host}"
    echo "networks:"
    echo "  mesh: {type: private, interface: eth0, cidrs: [${mesh_cidr}]}"
    echo "  host: {type: private, interface: lima1, cidrs: [${host_cidr}]}"
    echo "nodes:"
    for name in $(vms); do
      echo "  - name: ${name}"
      echo "    address: $(ip_of "$name" eth0)"
      echo "    addresses: {host: $(ip_of "$name")}"
      echo "    ssh: {user: ${user}, private_key: ${key}}"
      echo "    role: $([ "$name" = halab-1 ] && echo primary || echo replica)"
      echo "    datacenter: local"
    done
  } > "${CFG}/inventory.yml"
  if [ ! -f "${CFG}/ha.yml" ]; then
    sed -e "s/^db_engine: .*/db_engine: ${ENGINE}/" -e "s/^ha_provider: .*/ha_provider: ${HA}/" \
      config/ha.example.yml > "${CFG}/ha.yml"
  fi
  for f in benchmark monitoring; do [ -f "${CFG}/$f.yml" ] || cp "config/$f.example.yml" "${CFG}/$f.yml"; done
  if [ ! -f "${CFG}/secrets.yml" ]; then
    (umask 077; for k in db_exporter_password db_replication_password db_benchmark_password db_admin_password; do
      echo "$k: \"$(openssl rand -hex 16)\""; done > "${CFG}/secrets.yml")
  fi
  green "config: ${CFG}"
  echo "Next: export LAB_CONFIG_DIR=local/lab-vms/config && make validate provision targets monitoring ha"
}

down() {
  for name in $(vms); do limactl delete --force "$name" && yellow "$name deleted"; done
}

status() {
  for name in $(vms); do echo "$name $(limactl list --format '{{.Status}}' "$name") $(ip_of "$name" 2>/dev/null)"; done
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  status) status ;;
  *) echo "usage: local-lab.sh up|down|status   (env: N ENGINE HA CPUS MEM DISK)"; exit 1 ;;
esac
